import { APIRequestContext, APIResponse } from '@playwright/test';
import { env } from '../../config/env';
import { CreateRepositoryRequest } from '../models/GitHubModels';
import { ApiUtil } from '../utils/ApiUtil';
import { DataUtil } from '../utils/DataUtil';

export interface CreateRepositoryOptions {
  description?: string;
  isPrivate?: boolean;
  autoInit?: boolean;
}

export class GitHubRepositoryService {
  constructor(private readonly api: APIRequestContext) {}

  private static repoPath(owner: string, repo: string): string {
    return `/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}`;
  }

  /** GET /repos/{owner}/{repo} */
  getRepository(owner: string, repo: string): Promise<APIResponse> {
    return ApiUtil.send(this.api, 'GET', GitHubRepositoryService.repoPath(owner, repo));
  }

  /** GET /user/repos (repositories owned by the authenticated user) */
  listRepositories(perPage = 100, page = 1): Promise<APIResponse> {
    return ApiUtil.send(
      this.api,
      'GET',
      `/user/repos?affiliation=owner&sort=updated&per_page=${perPage}&page=${page}`,
    );
  }

  /** POST /user/repos - always creates under the authenticated user's own account. */
  createRepository(name: string, options: CreateRepositoryOptions = {}): Promise<APIResponse> {
    const payload: CreateRepositoryRequest = {
      name,
      description: options.description,
      private: options.isPrivate ?? false,
      auto_init: options.autoInit ?? true,
    };
    return ApiUtil.send(this.api, 'POST', '/user/repos', payload);
  }

  /**
   * DELETE /repos/{owner}/{repo} - GUARDED. Refuses to delete anything that is not a
   * repository generated by this framework under the configured test account.
   */
  async deleteRepository(owner: string, repo: string): Promise<APIResponse> {
    if (owner.toLowerCase() !== env.userId.toLowerCase()) {
      throw new Error(`Refusing to delete: owner "${owner}" is not the configured test account.`);
    }
    if (!DataUtil.isGeneratedRepositoryName(repo)) {
      throw new Error(`Refusing to delete "${repo}": it does not match the generated test-repository naming pattern.`);
    }
    if (repo.toLowerCase() === env.testRepo.toLowerCase()) {
      throw new Error(`Refusing to delete "${repo}": it is the dedicated capstone repository.`);
    }
    return ApiUtil.send(this.api, 'DELETE', GitHubRepositoryService.repoPath(owner, repo));
  }
}
